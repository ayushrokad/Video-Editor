// Backwards-compatibility mapping from legacy v1 DOM IDs to v2 Panel Registry IDs
export const LEGACY_PANEL_ID_MAP = {
  'panel-project': 'project',
  'panel-effects': 'effects-library',
  'panel-color-clips': 'lut-browser',
  'monitors-pane': 'program-monitor',
  'panel-inspector': 'properties',
  'panel-deliver-settings': 'export-settings',
  'panel-history': 'history',
  'panel-markers': 'markers',
  'panel-timeline': 'timeline',
  'panel-color-wheels': 'color-wheels',
  'panel-audio-console': 'audio-mixer',
  'panel-deliver-queue': 'render-queue',
};

export function normalizePanelId(id) {
  if (!id || typeof id !== 'string') return null;
  if (PANEL_REGISTRY[id]) return id;
  if (LEGACY_PANEL_ID_MAP[id]) return LEGACY_PANEL_ID_MAP[id];
  return null;
}

export function getPanelDefinition(id) {
  const norm = normalizePanelId(id);
  return norm ? PANEL_REGISTRY[norm] : null;
}

export function getPanelsByCategory() {
  const grouped = {};
  for (const cat of PANEL_CATEGORIES) grouped[cat] = [];
  for (const def of Object.values(PANEL_REGISTRY)) {
    if (!grouped[def.category]) grouped[def.category] = [];
    grouped[def.category].push(def);
  }
  return grouped;
}

export function getAllPanelIds() {
  return Object.keys(PANEL_REGISTRY);
}

